CREATE TABLE PRODUCTOS (
    ID_PRODUCTO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR2(20) NOT NULL,
    CATEGORIA VARCHAR2(20) NOT NULL,
    PRECIO NUMBER(10, 2) NOT NULL,
    CANTIDAD NUMBER NOT NULL,
    CONSTRAINT PK_PRODUCTOS PRIMARY KEY (ID_PRODUCTO),
    CONSTRAINT CHK_PRODUCTOS_NOMBRE
        CHECK (TRIM(NOMBRE) IS NOT NULL),
    CONSTRAINT CHK_PRODUCTOS_PRECIO
        CHECK (PRECIO >= 0),
    CONSTRAINT CHK_PRODUCTOS_CANTIDAD
        CHECK (CANTIDAD >= 0),
    CONSTRAINT CHK_PRODUCTOS_CATEGORIA
        CHECK (CATEGORIA IN (
            'ALIMENTO',
            'HIGIENE',
            'JUGUETE',
            'ELECTRONICA',
            'ROPA',
            'ACCESORIO',
            'FARMACIA'
        ))
);

CREATE TABLE SUCURSALES (
    ID_SUCURSAL NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR2(50) NOT NULL,
    DIRECCION VARCHAR2(150) NOT NULL,
    CONSTRAINT PK_SUCURSALES PRIMARY KEY (ID_SUCURSAL),
    CONSTRAINT UQ_SUCURSALES_NOMBRE UNIQUE (NOMBRE),
    CONSTRAINT CHK_SUCURSALES_NOMBRE
        CHECK (TRIM(NOMBRE) IS NOT NULL),
    CONSTRAINT CHK_SUCURSALES_DIRECCION
        CHECK (TRIM(DIRECCION) IS NOT NULL)
);

CREATE TABLE VENTAS (
    ID_VENTA NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ESTADO VARCHAR2(20) NOT NULL,
    FECHA DATE NOT NULL,
    ID_SUCURSAL NUMBER NOT NULL,
    CONSTRAINT PK_VENTAS PRIMARY KEY (ID_VENTA),
    CONSTRAINT FK_VENTAS_SUCURSAL
        FOREIGN KEY (ID_SUCURSAL)
        REFERENCES SUCURSALES(ID_SUCURSAL),
    CONSTRAINT CHK_VENTAS_ESTADO
        CHECK (ESTADO IN (
            'REGISTRADA',
            'CANCELADA'
        ))
);

CREATE TABLE DETALLES_VENTAS (
    ID_DETALLE_VENTA NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_VENTA NUMBER NOT NULL,
    ID_PRODUCTO NUMBER NOT NULL,
    CANTIDAD_PRODUCTO NUMBER NOT NULL,
    PRECIO_PRODUCTO NUMBER(10,2) NOT NULL,
    CONSTRAINT PK_DETALLES_VENTAS PRIMARY KEY (ID_DETALLE_VENTA),
    CONSTRAINT FK_DETALLE_VENTA
        FOREIGN KEY (ID_VENTA)
        REFERENCES VENTAS(ID_VENTA)
        ON DELETE CASCADE,
    CONSTRAINT FK_DETALLE_PRODUCTO
        FOREIGN KEY (ID_PRODUCTO)
        REFERENCES PRODUCTOS(ID_PRODUCTO),
    CONSTRAINT CHK_DETALLE_CANTIDAD
        CHECK (CANTIDAD_PRODUCTO > 0),
    CONSTRAINT CHK_DETALLE_PRECIO
        CHECK (PRECIO_PRODUCTO >= 0)
);